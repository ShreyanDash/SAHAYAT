package com.sahayat.app.data.service

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import com.sahayat.app.BuildConfig
import com.sahayat.app.core.AppError
import com.sahayat.app.core.Format
import com.sahayat.app.core.Outcome
import com.sahayat.app.data.model.DeviceStatus
import com.sahayat.app.data.model.Patient
import com.sahayat.app.data.model.SeizureEvent
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

data class ExportRequest(
    val patient: Patient,
    val fromMs: Long?,
    val toMs: Long?,
    val events: List<SeizureEvent>,
    val device: DeviceStatus?,
    val generatedBy: String,
)

data class ExportedFile(val file: File, val uri: Uri, val pageCount: Int, val eventCount: Int)

/** Renders seizure logs into a clean A4 PDF using the platform PdfDocument API (no third-party libs). */
class ExportService(private val context: Context) {

    suspend fun export(req: ExportRequest): Outcome<ExportedFile> = withContext(Dispatchers.IO) {
        runCatching { render(req) }
            .fold(
                onSuccess = { Outcome.Success(it) },
                onFailure = { Outcome.Failure(AppError.ExportFailed) },
            )
    }

    /** Copies a generated file to a user-chosen SAF destination. */
    suspend fun copyTo(file: File, destination: Uri): Outcome<Unit> = withContext(Dispatchers.IO) {
        runCatching {
            context.contentResolver.openOutputStream(destination)?.use { out ->
                file.inputStream().use { it.copyTo(out) }
            } ?: error("No output stream")
        }.fold({ Outcome.Success(Unit) }, { Outcome.Failure(AppError.ExportFailed) })
    }

    private fun render(req: ExportRequest): ExportedFile {
        val pageW = 595
        val pageH = 842
        val margin = 40f
        val doc = PdfDocument()

        val title = Paint().apply { color = Color.rgb(10, 15, 12); textSize = 20f; typeface = Typeface.DEFAULT_BOLD; isAntiAlias = true }
        val h2 = Paint().apply { color = Color.rgb(10, 15, 12); textSize = 12f; typeface = Typeface.DEFAULT_BOLD; isAntiAlias = true }
        val body = Paint().apply { color = Color.rgb(40, 48, 54); textSize = 9.5f; isAntiAlias = true }
        val muted = Paint().apply { color = Color.rgb(110, 120, 128); textSize = 8.5f; isAntiAlias = true }
        val accent = Paint().apply { color = Color.rgb(42, 201, 118); strokeWidth = 2f }
        val rule = Paint().apply { color = Color.rgb(220, 224, 228); strokeWidth = 0.7f }

        var pageNo = 0
        lateinit var page: PdfDocument.Page
        var y = 0f

        fun newPage() {
            if (pageNo > 0) doc.finishPage(page)
            pageNo++
            page = doc.startPage(PdfDocument.PageInfo.Builder(pageW, pageH, pageNo).create())
            y = margin
            page.canvas.drawText("SAHAYAT — Seizure Event Log", margin, pageH - 22f, muted)
            page.canvas.drawText("Page $pageNo", pageW - margin - 40f, pageH - 22f, muted)
        }

        fun ensure(space: Float) { if (y + space > pageH - 50f) newPage() }

        fun kv(k: String, v: String) {
            ensure(14f)
            page.canvas.drawText(k, margin, y, muted)
            page.canvas.drawText(v, margin + 120f, y, body)
            y += 14f
        }

        newPage()
        page.canvas.drawText("SAHAYAT Seizure Log", margin, y + 14f, title)
        y += 24f
        page.canvas.drawLine(margin, y, margin + 60f, y, accent)
        y += 20f

        page.canvas.drawText("Patient", margin, y, h2); y += 16f
        kv("Name", req.patient.name)
        req.patient.age?.let { kv("Age", it.toString()) }
        req.patient.bloodGroup?.let { kv("Blood group", it) }
        val range = when {
            req.fromMs == null && req.toMs == null -> "All recorded events"
            else -> "${req.fromMs?.let(Format::date) ?: "Beginning"} – ${req.toMs?.let(Format::date) ?: "Today"}"
        }
        kv("Date range", range)
        kv("Events", req.events.size.toString())
        kv("Generated", Format.dateTime(System.currentTimeMillis()))
        kv("Generated by", req.generatedBy)
        y += 8f

        page.canvas.drawText("Device", margin, y, h2); y += 16f
        val d = req.device
        if (d == null) {
            kv("Status", "No device information available")
        } else {
            kv("Device ID", d.deviceId)
            kv("Firmware", d.firmware ?: "Unavailable")
            kv("Last communication", d.lastSeenMs?.let(Format::dateTime) ?: "Unavailable")
        }
        y += 12f

        page.canvas.drawText("Events", margin, y, h2); y += 16f
        val cols = floatArrayOf(margin, margin + 78f, margin + 132f, margin + 180f, margin + 262f, margin + 318f, margin + 420f)
        val headers = listOf("Date", "Time", "Duration", "Status", "Response", "Responder", "Device")
        fun header() {
            ensure(20f)
            headers.forEachIndexed { i, h -> page.canvas.drawText(h, cols[i], y, muted) }
            y += 6f
            page.canvas.drawLine(margin, y, pageW - margin, y, rule)
            y += 12f
        }
        header()
        if (req.events.isEmpty()) {
            page.canvas.drawText("No events recorded in this range.", margin, y, body)
            y += 14f
        }
        req.events.sortedBy { it.detectedAtMs }.forEach { e ->
            if (y + 30f > pageH - 50f) { newPage(); header() }
            val cells = listOf(
                Format.date(e.detectedAtMs),
                Format.shortTime(e.detectedAtMs),
                Format.duration(e.durationSec) ?: "—",
                e.status.name.lowercase().replaceFirstChar { it.uppercase() } +
                    (if (e.escalatedAtMs != null) " (esc.)" else "") + (if (e.isTest) " [TEST]" else ""),
                Format.duration(e.responseTimeSec) ?: "—",
                (e.acknowledgedBy?.name ?: "—").take(18),
                (e.deviceId ?: "—").take(18),
            )
            cells.forEachIndexed { i, c -> page.canvas.drawText(c, cols[i], y, body) }
            y += 12f
            val extra = buildList {
                e.location?.let { add("Location %.5f, %.5f".format(it.lat, it.lng)) }
                if (e.escalatedAtMs != null) add("SMS fallback: ${e.smsStatus.name.lowercase()}")
            }
            if (extra.isNotEmpty()) {
                page.canvas.drawText(extra.joinToString("   ·   "), cols[1], y, muted)
                y += 11f
            }
            page.canvas.drawLine(margin, y - 3f, pageW - margin, y - 3f, rule)
            y += 6f
        }

        ensure(40f)
        y += 12f
        page.canvas.drawText(
            "Events are reported by the SAHAYAT wearable's detection algorithm and are not a medical diagnosis.",
            margin, y, muted,
        )
        y += 11f
        page.canvas.drawText("App version ${BuildConfig.VERSION_NAME}", margin, y, muted)
        doc.finishPage(page)

        val dir = File(context.cacheDir, "exports").apply { mkdirs() }
        dir.listFiles()?.forEach { it.delete() } // keep only the latest export on-device
        val file = File(dir, "sahayat_log_${System.currentTimeMillis()}.pdf")
        file.outputStream().use { doc.writeTo(it) }
        doc.close()
        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        return ExportedFile(file, uri, pageNo, req.events.size)
    }
}
